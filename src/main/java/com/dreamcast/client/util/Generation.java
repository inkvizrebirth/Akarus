package com.dreamcast.client.util;

/**
 * Поколения фоновых задач экрана: {@code removed()} повышает поколение, и все
 * незавершённые задачи со «билетом» старого поколения игнорируются.
 *
 * <p>Закрывает гонку «иконки миров читались в фоне, а экран уже закрыли»:
 * текстуры к моменту завершения задачи могут быть освобождены, и заливка в
 * них упала бы. С билетом задача видит, что она устарела, и просто
 * освобождает свои ресурсы.</p>
 */
public final class Generation {

	private int value;

	/** Билет задачи: действителен, пока поколение не сдвинулось. */
	public record Ticket(int value) {
	}

	/** Выдать билет текущего поколения (вызывается при старте фоновой задачи). */
	public Ticket start() {
		return new Ticket(value);
	}

	/** Поднять поколение: все ранее выданные билеты становятся недействительными. */
	public void invalidate() {
		value++;
	}

	/** Действителен ли ещё билет (вызывается в completion на потоке игры). */
	public boolean valid(Ticket ticket) {
		return ticket.value() == value;
	}
}
